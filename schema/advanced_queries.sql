WHERE p.ID_PARTICIPANTE IN (
    SELECT i2.ID_PARTICIPANTE
    FROM RL_INSCRICAO_HISTORICO i2
    GROUP BY i2.ID_PARTICIPANTE
    HAVING COUNT(DISTINCT i2.ID_ATIVIDADE) > 1
);

