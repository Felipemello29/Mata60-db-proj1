-- [RF2] Query 15: First activity date for each participant, only those enrolled in >2 activities
-- Requisito: RF2 - Enrollment, attendance control, participation history
-- Tabelas: TB_PARTICIPANTE, RL_INSCRICAO_HISTORICO, TB_ATIVIDADE
-- Funções: JOIN, WINDOW (FIRST_VALUE), SUB-QUERY
SELECT DISTINCT
    p.DS_NOME_PARTICIPANTE,
