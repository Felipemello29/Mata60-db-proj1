-- [RF6] Query 1: Rank participants by average grade across all activities
-- Requisito: RF6 - Grade control for extension courses
-- Tabelas: TB_PARTICIPANTE, RL_INSCRICAO_HISTORICO, TB_ATIVIDADE
-- Funções: JOIN, GROUP BY, WINDOW (RANK)
SELECT
    sub.DS_NOME_PARTICIPANTE,
    sub.media_global,
    RANK() OVER(ORDER BY sub.media_global DESC) AS RANKING
FROM (
    SELECT
        p.ID_PARTICIPANTE,
        p.DS_NOME_PARTICIPANTE,
        AVG(i.VL_NOTA_AVALIACAO) AS MEDIA_GLOBAL
    FROM TB_PARTICIPANTE p
    JOIN RL_INSCRICAO_HISTORICO i ON p.ID_PARTICIPANTE = i.ID_PARTICIPANTE
    JOIN TB_ATIVIDADE a ON i.ID_ATIVIDADE = a.ID_ATIVIDADE
    GROUP BY p.ID_PARTICIPANTE, p.DS_NOME_PARTICIPANTE
) sub;

-- [RF3] Query 2: Find the top 3 projects by total number of certificates issued
-- Requisito: RF3 - Automatic certificate issuance after activity completion
-- Tabelas: TB_PROJETO_EXTENSAO, TB_ATIVIDADE, RL_INSCRICAO_HISTORICO, TB_EMISSAO_CERTIFICADO
-- Funções: SUB-QUERY, JOIN, GROUP BY, COUNT
SELECT DS_NOME_PROJETO, total_certificados
FROM (
    SELECT proj.DS_NOME_PROJETO, COUNT(cert.ID_CERTIFICADO) AS TOTAL_CERTIFICADOS
    FROM TB_PROJETO_EXTENSAO proj
    JOIN TB_ATIVIDADE a ON proj.ID_PROJETO = a.ID_PROJ_VINCULADO
    JOIN RL_INSCRICAO_HISTORICO i ON a.ID_ATIVIDADE = i.ID_ATIVIDADE
    JOIN TB_EMISSAO_CERTIFICADO cert ON i.ID_INSCRICAO = cert.ID_INSCRICAO
    GROUP BY proj.DS_NOME_PROJETO
) sub
ORDER BY total_certificados DESC
LIMIT 3;

-- [RF2] Query 3: Activities with participation higher than the average, showing project name
-- Requisito: RF2 - Enrollment, attendance control, participation history
-- Tabelas: TB_ATIVIDADE, RL_INSCRICAO_HISTORICO, TB_PROJETO_EXTENSAO
-- Funções: SUB-QUERY, JOIN, GROUP BY, COUNT
WITH AtividadeContagem AS (
    SELECT ID_ATIVIDADE, COUNT(*) AS TOTAL_INSCRITOS
    FROM RL_INSCRICAO_HISTORICO
    GROUP BY ID_ATIVIDADE
)
SELECT a.DS_TITULO_ATIVIDADE, proj.DS_NOME_PROJETO, ac.total_inscritos
FROM TB_ATIVIDADE a
JOIN AtividadeContagem ac ON a.ID_ATIVIDADE = ac.ID_ATIVIDADE
JOIN TB_PROJETO_EXTENSAO proj ON a.ID_PROJ_VINCULADO = proj.ID_PROJETO
WHERE ac.total_inscritos > (SELECT AVG(total_inscritos) FROM AtividadeContagem);

-- [RF7] Query 4: Instructors who never coordinated a project but are allocated to activities
-- Requisito: RF7 - Extension project management (members, coordinators)
-- Tabelas: TB_INSTRUTOR, RL_ALOCACAO_INSTRUTOR, TB_ATIVIDADE, TB_PROJETO_EXTENSAO
-- Funções: SUB-QUERY (NOT EXISTS), JOIN, GROUP BY, COUNT
SELECT
    inst.DS_NOME_INSTRUTOR,
    COUNT(DISTINCT alloc.ID_ATIVIDADE) AS TOTAL_ATIVIDADES_ALOCADAS
FROM TB_INSTRUTOR inst
JOIN RL_ALOCACAO_INSTRUTOR alloc ON inst.ID_INSTRUTOR = alloc.ID_INSTRUTOR
JOIN TB_ATIVIDADE a ON alloc.ID_ATIVIDADE = a.ID_ATIVIDADE
WHERE NOT EXISTS (
    SELECT 1 FROM TB_PROJETO_EXTENSAO proj
    WHERE proj.ID_INSTR_COORDENADOR = inst.ID_INSTRUTOR
)
GROUP BY inst.ID_INSTRUTOR, inst.DS_NOME_INSTRUTOR;

-- [RF5] Query 5: Running total of sponsorship contributions per partner with activity names
-- Requisito: RF5 - Partnership management, impact/participation reports
-- Tabelas: TB_PARCEIRO, RL_PATROCINIO_EVENTO, TB_ATIVIDADE
-- Funções: JOIN, WINDOW (SUM), COUNT
SELECT
    p.DS_NOME_ORGANIZACAO,
    a.DS_TITULO_ATIVIDADE,
    pat.VL_APORTE,
    SUM(pat.VL_APORTE) OVER(PARTITION BY p.ID_PARCEIRO ORDER BY a.ID_ATIVIDADE) AS TOTAL_ACUMULADO,
    COUNT(*) OVER(PARTITION BY p.ID_PARCEIRO) AS TOTAL_PATROCINIOS_PARCEIRO
FROM TB_PARCEIRO p
JOIN RL_PATROCINIO_EVENTO pat ON p.ID_PARCEIRO = pat.ID_PARCEIRO
JOIN TB_ATIVIDADE a ON pat.ID_ATIVIDADE = a.ID_ATIVIDADE;

-- [RF6] Query 6: Participant grade AS PERCENTAGE of max grade, only for activities with >5 enrollments
-- Requisito: RF6 - Grade control for extension courses
-- Tabelas: TB_PARTICIPANTE, RL_INSCRICAO_HISTORICO, TB_ATIVIDADE
-- Funções: JOIN, WINDOW, SUB-QUERY
SELECT
    p.DS_NOME_PARTICIPANTE,
    a.DS_TITULO_ATIVIDADE,
    i.VL_NOTA_AVALIACAO,
    (i.VL_NOTA_AVALIACAO / MAX(i.VL_NOTA_AVALIACAO) OVER(PARTITION BY a.ID_ATIVIDADE)) * 100 AS PERC_MAX_NOTA
FROM TB_PARTICIPANTE p
JOIN RL_INSCRICAO_HISTORICO i ON p.ID_PARTICIPANTE = i.ID_PARTICIPANTE
JOIN TB_ATIVIDADE a ON i.ID_ATIVIDADE = a.ID_ATIVIDADE
WHERE a.ID_ATIVIDADE IN (
    SELECT ID_ATIVIDADE
    FROM RL_INSCRICAO_HISTORICO
    GROUP BY ID_ATIVIDADE
    HAVING COUNT(*) > 5
);

-- [RF7] Query 7: Projects where the coordinator also teaches, only projects with >5 activities
-- Requisito: RF7 - Extension project management (members, coordinators)
-- Tabelas: TB_PROJETO_EXTENSAO, TB_ATIVIDADE, RL_ALOCACAO_INSTRUTOR
-- Funções: JOIN, GROUP BY, COUNT, SUB-QUERY
SELECT proj.DS_NOME_PROJETO, (SELECT COUNT(*) FROM TB_ATIVIDADE WHERE ID_PROJ_VINCULADO = proj.ID_PROJETO) AS TOTAL_ATIVIDADES
FROM TB_PROJETO_EXTENSAO proj
WHERE EXISTS (
    SELECT 1 FROM TB_ATIVIDADE a
    JOIN RL_ALOCACAO_INSTRUTOR alloc ON a.ID_ATIVIDADE = alloc.ID_ATIVIDADE
    WHERE a.ID_PROJ_VINCULADO = proj.ID_PROJETO
    AND alloc.ID_INSTRUTOR = proj.ID_INSTR_COORDENADOR
)
AND proj.ID_PROJETO IN (
    SELECT ID_PROJ_VINCULADO
    FROM TB_ATIVIDADE
    GROUP BY ID_PROJ_VINCULADO
    HAVING COUNT(*) > 5
);

-- [RF7] Query 8: Projects with more than average 'ALUNO' participants
-- Requisito: RF7 - Extension project management (members, coordinators)
-- Tabelas: TB_PROJETO_EXTENSAO, RL_MEMBRO_PROJETO, TB_PARTICIPANTE
-- Funções: JOIN, GROUP BY, COUNT, SUB-QUERY
SELECT proj.DS_NOME_PROJETO, COUNT(p.ID_PARTICIPANTE) AS TOTAL_ALUNOS
FROM TB_PROJETO_EXTENSAO proj
JOIN RL_MEMBRO_PROJETO mem ON proj.ID_PROJETO = mem.ID_PROJETO
JOIN TB_PARTICIPANTE p ON mem.ID_PARTICIPANTE = p.ID_PARTICIPANTE
WHERE p.TP_VINCULO_INST = 'ALUNO'
GROUP BY proj.DS_NOME_PROJETO
HAVING COUNT(p.ID_PARTICIPANTE) > (
    SELECT AVG(alunos_count) FROM (
        SELECT COUNT(p2.ID_PARTICIPANTE) AS ALUNOS_COUNT
        FROM RL_MEMBRO_PROJETO mem2
        JOIN TB_PARTICIPANTE p2 ON mem2.ID_PARTICIPANTE = p2.ID_PARTICIPANTE
        WHERE p2.TP_VINCULO_INST = 'ALUNO'
        GROUP BY mem2.ID_PROJETO
    ) sub
);

