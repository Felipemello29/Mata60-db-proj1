-- [RF4] Query 17: Participant with lowest feedback score in a highly attended activity (>20 people)
-- Requisito: RF4 - Participant feedback registration
-- Tabelas: TB_PARTICIPANTE, RL_INSCRICAO_HISTORICO, TB_REGISTRO_FEEDBACK, TB_ATIVIDADE
-- Funções: SUB-QUERY, JOIN, GROUP BY (in sub-query), COUNT (HAVING)
SELECT p.DS_NOME_PARTICIPANTE, f.VL_NOTA_SATISFACAO, a.DS_TITULO_ATIVIDADE
FROM TB_PARTICIPANTE p
JOIN RL_INSCRICAO_HISTORICO i ON p.ID_PARTICIPANTE = i.ID_PARTICIPANTE
JOIN TB_REGISTRO_FEEDBACK f ON i.ID_INSCRICAO = f.ID_INSCRICAO
