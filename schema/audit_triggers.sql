-- 2. Create Audit Functions

CREATE OR REPLACE FUNCTION FC_AUDIT_TB_ATIVIDADE()
RETURNS TRIGGER AS $$
DECLARE
    v_app_user VARCHAR(100);
BEGIN
    v_app_user := COALESCE(nullif(current_setting('app.usuario', true), ''), current_user);
    IF (TG_OP = 'DELETE') THEN
        INSERT INTO TA_TB_ATIVIDADE (ID_ATIVIDADE, DS_TITULO_ATIVIDADE, DS_CONTEUDO_PROG, DT_REALIZACAO, ID_PROJ_VINCULADO, TP_OPERACAO, NM_USUARIO_BD, NM_USUARIO_APLICACAO, NM_TERMINAL)
        VALUES (OLD.ID_ATIVIDADE, OLD.DS_TITULO_ATIVIDADE, OLD.DS_CONTEUDO_PROG, OLD.DT_REALIZACAO, OLD.ID_PROJ_VINCULADO, 'D', current_user, v_app_user, inet_client_addr()::varchar);
        RETURN OLD;
    ELSIF (TG_OP = 'UPDATE') THEN
        INSERT INTO TA_TB_ATIVIDADE (ID_ATIVIDADE, DS_TITULO_ATIVIDADE, DS_CONTEUDO_PROG, DT_REALIZACAO, ID_PROJ_VINCULADO, TP_OPERACAO, NM_USUARIO_BD, NM_USUARIO_APLICACAO, NM_TERMINAL)
        VALUES (NEW.ID_ATIVIDADE, NEW.DS_TITULO_ATIVIDADE, NEW.DS_CONTEUDO_PROG, NEW.DT_REALIZACAO, NEW.ID_PROJ_VINCULADO, 'U', current_user, v_app_user, inet_client_addr()::varchar);
        RETURN NEW;
    ELSIF (TG_OP = 'INSERT') THEN
        INSERT INTO TA_TB_ATIVIDADE (ID_ATIVIDADE, DS_TITULO_ATIVIDADE, DS_CONTEUDO_PROG, DT_REALIZACAO, ID_PROJ_VINCULADO, TP_OPERACAO, NM_USUARIO_BD, NM_USUARIO_APLICACAO, NM_TERMINAL)
        VALUES (NEW.ID_ATIVIDADE, NEW.DS_TITULO_ATIVIDADE, NEW.DS_CONTEUDO_PROG, NEW.DT_REALIZACAO, NEW.ID_PROJ_VINCULADO, 'I', current_user, v_app_user, inet_client_addr()::varchar);
        RETURN NEW;
    END IF;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

