-- 3. Create Triggers (TG_A_[I/U/D]_)

CREATE TRIGGER TG_A_IUD_TB_ATIVIDADE
AFTER INSERT OR UPDATE OR DELETE ON TB_ATIVIDADE
FOR EACH ROW EXECUTE FUNCTION FC_AUDIT_TB_ATIVIDADE();

CREATE TRIGGER TG_A_IUD_RL_INSCRICAO
AFTER INSERT OR UPDATE OR DELETE ON RL_INSCRICAO_HISTORICO
FOR EACH ROW EXECUTE FUNCTION FC_AUDIT_RL_INSCRICAO_HISTORICO();
