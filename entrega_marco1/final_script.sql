-- Compliant with MAD1: VW_ prefix, simplify complex queries, restrict access

-- [RF5] VW_IMPACTO_PROJETO: Impact summary per project (enrollments, certificates, avg satisfaction)
CREATE OR REPLACE VIEW VW_IMPACTO_PROJETO AS
SELECT
    proj.ID_PROJETO,
    proj.DS_NOME_PROJETO,
    COUNT(DISTINCT i.ID_INSCRICAO) AS total_inscricoes,
    COUNT(DISTINCT cert.ID_CERTIFICADO) AS total_certificados,
    ROUND(AVG(f.VL_NOTA_SATISFACAO), 2) AS media_satisfacao
FROM TB_PROJETO_EXTENSAO proj
LEFT JOIN TB_ATIVIDADE a ON proj.ID_PROJETO = a.ID_PROJ_VINCULADO
LEFT JOIN RL_INSCRICAO_HISTORICO i ON a.ID_ATIVIDADE = i.ID_ATIVIDADE
LEFT JOIN TB_EMISSAO_CERTIFICADO cert ON i.ID_INSCRICAO = cert.ID_INSCRICAO
LEFT JOIN TB_REGISTRO_FEEDBACK f ON i.ID_INSCRICAO = f.ID_INSCRICAO
GROUP BY proj.ID_PROJETO, proj.DS_NOME_PROJETO;

-- [RF2] VW_PARTICIPANTE_ATIVO: Participants with at least 1 presence
CREATE OR REPLACE VIEW VW_PARTICIPANTE_ATIVO AS
SELECT
    p.ID_PARTICIPANTE,
    p.DS_NOME_PARTICIPANTE,
    p.DS_EMAIL_CONTATO,
    p.TP_VINCULO_INST,
    COUNT(i.ID_INSCRICAO) AS total_presencas
FROM TB_PARTICIPANTE p
JOIN RL_INSCRICAO_HISTORICO i ON p.ID_PARTICIPANTE = i.ID_PARTICIPANTE
WHERE i.ST_PRESENCA = 'PRESENTE'
GROUP BY p.ID_PARTICIPANTE, p.DS_NOME_PARTICIPANTE, p.DS_EMAIL_CONTATO, p.TP_VINCULO_INST;

-- [RF5] VW_PARCEIRO_APORTE: Partners and total sponsorship value
CREATE OR REPLACE VIEW VW_PARCEIRO_APORTE AS
SELECT
    par.ID_PARCEIRO,
    par.DS_NOME_ORGANIZACAO,
    par.TP_PARCEIRO,
    COUNT(DISTINCT pat.ID_ATIVIDADE) AS total_atividades_apoiadas,
    COALESCE(SUM(pat.VL_APORTE), 0) AS total_aportado
FROM TB_PARCEIRO par
LEFT JOIN RL_PATROCINIO_EVENTO pat ON par.ID_PARCEIRO = pat.ID_PARCEIRO
GROUP BY par.ID_PARCEIRO, par.DS_NOME_ORGANIZACAO, par.TP_PARCEIRO;

-- [RF3] VW_CERTIFICADO_EMITIDO: All issued certificates with participant and activity
CREATE OR REPLACE VIEW VW_CERTIFICADO_EMITIDO AS
SELECT
    cert.ID_CERTIFICADO,
    cert.CD_AUTENTICIDADE,
    cert.DT_EMISSAO,
    p.DS_NOME_PARTICIPANTE,
    a.DS_TITULO_ATIVIDADE,
    a.DT_REALIZACAO
FROM TB_EMISSAO_CERTIFICADO cert
JOIN RL_INSCRICAO_HISTORICO i ON cert.ID_INSCRICAO = i.ID_INSCRICAO
JOIN TB_PARTICIPANTE p ON i.ID_PARTICIPANTE = p.ID_PARTICIPANTE
JOIN TB_ATIVIDADE a ON i.ID_ATIVIDADE = a.ID_ATIVIDADE;

